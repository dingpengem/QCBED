def elastic_atomic_scattering_factor(
    atomic_number: int, stl_inverse_angstrom: float, *, option: int = 2
) -> float:
    """Return the legacy OPTION=2 elastic factor as a Python binary64 float.

    Neutral atoms Z=1..98; 0 <= STL <= 6 inverse angstroms, except hydrogen
    has STL <= 1.5. STL is sin(theta)/lambda, not |g| or |g| squared.
    Output retains the source's 47.878009 / 1.145896 potential-factor scaling;
    it is not the unscaled electron scattering length. No volume division,
    thermal damping, absorption or gas randomization is included.

    OPTION=1 is the source X-ray branch and is outside this elastic-electron
    API. Bool and non-scalar/non-numeric inputs are rejected. Exact executable
    equivalence is unverified, including default-kind Fortran literal rounding.
    """
    if isinstance(atomic_number, bool) or not isinstance(atomic_number, Integral):
        raise TypeError("atomic_number must be an integer, not bool")
    if not 1 <= atomic_number <= 98:
        raise ValueError("atomic_number must be in 1..98")
    if isinstance(option, bool) or not isinstance(option, Integral):
        raise TypeError("option must be an integer, not bool")
    if option != 2:
        raise ValueError("option must be 2 (elastic electron scattering)")
    if isinstance(stl_inverse_angstrom, bool) or not isinstance(stl_inverse_angstrom, Real):
        raise TypeError("stl_inverse_angstrom must be a real scalar, not bool")
    try:
        stl = float(stl_inverse_angstrom)
    except OverflowError as exc:
        raise ValueError("stl_inverse_angstrom must be finite") from exc
    limit = 1.5 if atomic_number == 1 else 6.0
    if not math.isfinite(stl) or not 0.0 <= stl <= limit:
        raise ValueError(f"stl_inverse_angstrom must be finite and in 0..{limit}")
    z = int(atomic_number) - 1
    mott = _METHOD[z] == 2
    values = _XF[z] if mott else _EF[z]
    # Source PT(2): last usable table entry at or below STL. Negative entries
    # (-1 missing, -2 rejected by source authors) must not enter interpolation.
    p2 = max(i for i, x in enumerate(_STL) if x <= stl and values[i] >= 0.0)
    def following(index: int) -> int:
        return next((i for i in range(index + 1, 62) if values[i] >= 0.0), 62)
    p3 = following(p2)
    p4 = following(p3)
    sign = 1.0
    # Retain the one-based source reflection PP=ABS(PT(1))+2 near the origin.
    candidate = p2 + 1
    while True:
        candidate -= 1
        if candidate < 1:
            sign = -1.0
            pp = abs(candidate) + 2
        else:
            pp = candidate
        if values[pp - 1] >= 0.0:
            p1 = pp - 1
            break
    if p4 >= 62:
        usable = [i for i, value in enumerate(values) if value >= 0.0]
        p1, p2, p3, p4 = usable[-4:]
    s1, s2, s3, s4 = _STL[p1] * sign, _STL[p2], _STL[p3], _STL[p4]
    alpha, beta, gamma, delta = values[p1], values[p2], values[p3], values[p4]
    # Same coefficient order and arithmetic grouping as the readable Fortran.
    f1 = 1.0 / ((s1 - s2) * (s1 - s3))
    f2 = 1.0 / ((s2 - s3) * (s1 - s3))
    f3 = 1.0 / ((s2 - s3) * (s2 - s4))
    f4 = 1.0 / ((s3 - s4) * (s2 - s4))
    d13 = s1*s1*s1 - s2*s2*s2
    d23 = s2*s2*s2 - s3*s3*s3
    d33 = s3*s3*s3 - s4*s4*s4
    dt1, dt2, dt3 = alpha - beta, beta - gamma, gamma - delta
    d22, d21 = s2*s2 - s3*s3, s2 - s3
    a = (f1*dt1 - (f2+f3)*dt2 + f4*dt3) / (f1*d13 - (f2+f3)*d23 + f4*d33)
    b = f1*(dt1-a*d13) + f2*(a*d23-dt2)
    c = (beta-gamma-a*d23-b*d22) / d21
    d = beta - a*s2*s2*s2 - b*s2*s2 - c*s2
    factor = a*stl*stl*stl + b*stl*stl + c*stl + d
    if mott:
        if stl == 0.0:
            return float(_EF[z][0] * 47.878009)
        return float(1.145896 * (int(atomic_number) - factor) / (stl * stl))
    return float(factor * 47.878009)
